# Integer
x = 10
print(x)
print(type(x))

# Float
y = 3.23
print(y)
print(type(y))

# Complex
x = 2 + 3
y = 4j
print(x)
print(y)
print(type(x))
print(type(y))

# String
x = "Aung"
print(x)
print(type(x))

# Boolean
x = 2 == 4
y = 2 != 4
print(x)
print(y)
print(type(x))
print(type(y))

# Type Conversion
x = 3.14
y = int(x)
print(y)
print(type(y))
x = 10
y = float(x)
print(y)
print(type(y))
