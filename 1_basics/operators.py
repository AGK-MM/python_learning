# Arithmetic Operators
x = 10
y = 5
# Addition
print(x + y)

# Subtraction
print(x - y)

# Multiplication
print(x * y)

# Division
print(x / y)

# Floor Division
print(x // y)

# Modulus
print(x % y)

# Exponentiation
print(x**y)

# Assignment Operators
x = 10
print(x)
x += 5
print(x)
x -= 3
print(x)

# Comparison Operators
x = 10
y = 5
print(x == y)
print(x != y)
print(x > y)
print(x < y)
print(x >= y)
print(x <= y)

# Logical Operators
x = True
y = False
print(x and y)
print(x or y)
print(not x)
print(not y)

# Identity Operators
x = 10
y = 10
print(id(x))
print(id(y))
print(x is y)
print(x is not y)

# Membership Operators
x = [1, 2, 3, 4, 5]
y = 3
print(y in x)
print(y not in x)

# Bitwise Operators
x = 10
y = 4
print(bin(x))
print(bin(y))

print(x & y)
print(x | y)
print(x ^ y)
print(~x)
print(x << 1)
print(x >> 1)
